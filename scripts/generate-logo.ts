// Regenerates the Swinford mark from the Calabi–Yau quintic and writes it everywhere it's used:
//   src/lib/mark.ts           path data for the <Mark> component
//   static/favicon.svg        tab icon
//   static/favicon.png        raster fallback
//   static/apple-touch-icon.png
//
// The mark has three cuts of the same view: a fine line screen for display sizes, a coarse
// one for small sizes where the fine stripes would blur to grey, and a solid silhouette.
// Both icons are the coarse screen on a white tile; the tab icon redraws it to the pixel grid
// of a 16px tab at 2x.
//
// Usage: npm run logo

import { writeFileSync } from 'node:fs';
import { Resvg } from '@resvg/resvg-js';
import { diagonal, fit, project, quinticMesh } from '#lib/logo/quintic.ts';
import { BOX, coarse, fine, type ScreenOptions } from '#lib/logo/screen.ts';
import { lineScreen } from './logo/screen.ts';
import { silhouette, toPathData } from './logo/silhouette.ts';

const INK = '#0a0a0a';
const root = new URL('../', import.meta.url);

const mesh = quinticMesh({ nx: 12, ny: 12 });
const faces = project(mesh, diagonal, fit(mesh, diagonal, BOX));
const outline = silhouette(
	faces.map((face) => face.points),
	{ tolerance: 0.3, minArea: 1 }
);
const solidRings = silhouette(
	faces.map((face) => face.points),
	{ tolerance: 1.2 }
);
const screenRings = lineScreen(faces, outline, fine);
const screenSmallRings = lineScreen(faces, outline, coarse);

// The tab icon spans 32 pixels with the mark inset `TAB_INSET` of them. It's the coarse screen
// scaled so each stripe gets exactly two pixels, laid from the top of the tile so every bar's
// top edge is crisp.
const TAB_INSET = 2;
const tabBox = (BOX * 32) / (32 - 2 * TAB_INSET);
const tabPad = (tabBox - BOX) / 2;
const k = (2 * tabBox) / 32 / coarse.pitch;
const tab: ScreenOptions = { ...coarse, pitch: coarse.pitch * k, minRun: coarse.minRun * k };
const tabRings = lineScreen(faces, outline, tab, { top: -tabPad });

const solid = toPathData(solidRings);
const screen = toPathData(screenRings);
const screenSmall = toPathData(screenSmallRings);
const tabIcon = toPathData(tabRings);
const viewBox = `0 0 ${BOX} ${BOX}`;

writeFileSync(
	new URL('src/lib/mark.ts', root),
	`// Generated by \`npm run logo\` (scripts/generate-logo.ts). Do not edit by hand.\n` +
		`// Calabi–Yau quintic z₁⁵ + z₂⁵ = 1, three-quarter view.\n\n` +
		`export const viewBox = '${viewBox}';\n\n` +
		`/** Silhouette. */\nexport const solid =\n\t'${solid}';\n\n` +
		`/** Line screen, for display sizes. */\nexport const screen =\n\t'${screen}';\n\n` +
		`/** Coarse line screen, for sizes below 64px. */\nexport const screenSmall =\n\t'${screenSmall}';\n`
);

/** `d` centered on a white tile `size` units wide, with corners rounded by `radius`. */
const tile = (d: string, box: number, corner = 0) => {
	const [size, o, radius] = [box, (box - BOX) / 2, corner].map((v) => Number(v.toFixed(2)));
	return (
		`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-o} ${-o} ${size} ${size}">` +
		`<rect x="${-o}" y="${-o}" width="${size}" height="${size}" rx="${radius}" fill="#fff"/>` +
		`<path d="${d}" fill="${INK}" fill-rule="evenodd"/></svg>`
	);
};
const png = (svg: string, width: number) =>
	new Resvg(svg, { fitTo: { mode: 'width', value: width } }).render().asPng();

const favicon = tile(tabIcon, tabBox, 0.22 * tabBox);
writeFileSync(new URL('static/favicon.svg', root), `${favicon}\n`);
writeFileSync(new URL('static/favicon.png', root), png(favicon, 64));
// iOS rounds the corners itself and wants the mark well inside them.
writeFileSync(
	new URL('static/apple-touch-icon.png', root),
	png(tile(screenSmall, BOX / (1 - 2 * 0.18)), 180)
);

console.log(
	`mark: viewBox ${viewBox}; solid ${solidRings.length} rings, ${solid.length} bytes; ` +
		`screen ${screenRings.length} bars, ${(screen.length / 1024).toFixed(1)} KB; ` +
		`small screen ${screenSmallRings.length} bars, ${(screenSmall.length / 1024).toFixed(1)} KB; ` +
		`tab icon ${tabRings.length} rings, ${tabIcon.length} bytes`
);
